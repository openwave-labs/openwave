# ------------------------------------------------------------------ decomposition machinery
def qc_to_sym(M):
    return sp.Matrix(len(M), len(M[0]), lambda i, k: M[i][k].to_sympy())


def to_orth(Pm, n):
    return sp.Matrix(n + 1, n + 1, lambda ap, a: Pm[ap, a] * sp.sqrt(fact_weight(n, ap) / fact_weight(n, a)))


def exact_simplify(e):
    e = sp.nsimplify(sp.radsimp(sp.expand(e)), rational=False) if False else sp.radsimp(sp.expand(e))
    return sp.simplify(e)


def decompose(n, seed=12345):
    """Isotypic decomposition of V_{n/2} restricted to Gamma."""
    Zc = []
    for C in classes:
        acc = [[QC(0)] * (n + 1) for _ in range(n + 1)]
        for g in C:
            D = D_mono(g.su2(), n)
            acc = [[acc[i][k] + D[i][k] for k in range(n + 1)] for i in range(n + 1)]
        Zc.append(acc)
    rnd = random.Random(seed)
    coeffs = [rnd.randint(-7, 7) for _ in classes]
    Z = [[sum((c * Zc[t][i][k] for t, c in enumerate(coeffs)), QC(0)) for k in range(n + 1)]
         for i in range(n + 1)]
    mp = qc_minpoly(Z)
    lam = sp.symbols("lam")
    poly = sum(c.to_sympy() * lam ** i for i, c in enumerate(mp))
    rts = sp.roots(sp.Poly(sp.expand(poly), lam))
    assert sum(rts.values()) == len(mp) - 1 and all(m == 1 for m in rts.values()), rts
    roots = [sp.radsimp(r) for r in rts]
    Zs = qc_to_sym(Z)
    Zcs = [qc_to_sym(M) for M in Zc]
    Id = sp.eye(n + 1)
    comps = []
    for i, li in enumerate(roots):
        P = Id
        for k, lk in enumerate(roots):
            if k != i:
                P = P * (Zs - lk * Id) / (li - lk)
        P = P.applyfunc(lambda e: sp.radsimp(sp.expand(e)))
        # checks in the monomial basis
        assert (P * P - P).applyfunc(lambda e: sp.simplify(e)) == sp.zeros(n + 1), "idempotent"
        d = sp.simplify(P.trace())
        # each class sum acts as a scalar on the image
        chi = []
        for t, C in enumerate(classes):
            ZP = Zcs[t] * P
            mu = sp.simplify((ZP).trace() / d)
            assert (ZP - mu * P).applyfunc(lambda e: sp.simplify(e)) == sp.zeros(n + 1), "central"
            chi.append(sp.simplify(sp.radsimp((Zcs[t] * P).trace() / len(C))))
        normchi = sp.simplify(sum(len(C) * chi[t] * sp.conjugate(chi[t])
                                  for t, C in enumerate(classes)) / 120)
        # character-formula projector reproduces P  (P' = (d_sigma/|G|) sum conj(chi) Z_C), with
        # d_sigma = d / m and m^2 = <chi,chi>
        m = sp.sqrt(normchi)
        dsig = d / m
        Pchar = sum((sp.conjugate(chi[t]) * Zcs[t] for t in range(len(classes))),
                    sp.zeros(n + 1)) * dsig / 120
        char_ok = (Pchar - P).applyfunc(lambda e: sp.simplify(e)) == sp.zeros(n + 1)
        Po = to_orth(P, n).applyfunc(lambda e: sp.radsimp(sp.expand(e)))
        herm = (Po - Po.H).applyfunc(lambda e: sp.simplify(e)) == sp.zeros(n + 1)
        D1o = to_orth(qc_to_sym(D_mono(Q1.su2(), n)), n)
        D2o = to_orth(qc_to_sym(D_mono(Q2.su2(), n)), n)
        comm = all((Do * Po - Po * Do).applyfunc(lambda e: sp.simplify(e)) == sp.zeros(n + 1)
                   for Do in (D1o, D2o))
        # Frobenius-Schur indicator of the constituent (valid when m = 1)
        fs = sp.simplify(sum(chi[cls_of[g * g]] for g in G) / 120) if m == 1 else None
        comps.append({"eigenvalue_of_random_class_combination": li, "rank": d, "chi": chi,
                      "norm_chi": normchi, "multiplicity": m, "irrep_dim": dsig,
                      "P_mono": P, "P_orth": Po, "hermitian": herm, "commutes_with_D": comm,
                      "character_projector_matches": char_ok, "FS": fs})
    chiV = [sum(c["chi"][t] for c in comps) for t in range(len(classes))]
    normV = sp.simplify(sum(len(C) * chiV[t] * sp.conjugate(chiV[t])
                            for t, C in enumerate(classes)) / 120)
    return comps, normV, coeffs


