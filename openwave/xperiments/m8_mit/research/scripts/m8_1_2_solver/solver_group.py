# ------------------------------------------------------------------ item 10: invariants
def chi_spin(n, w):
    """Character of V_{n/2} at an element with real part w: Chebyshev U_n(w)."""
    U0, U1 = Q5(1), 2 * w
    if n == 0:
        return U0
    for _ in range(n - 1):
        U0, U1 = U1, 2 * w * U1 - U0
    return U1


def dim_inv(n):
    tot = Q5(0)
    for C in classes:
        tot = tot + len(C) * chi_spin(n, C[0].w)
    tot = tot / 120
    assert tot.b == 0 and tot.a.denominator == 1
    return int(tot.a)


