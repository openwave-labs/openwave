def seed_of(T: Terms, kind):
    """the R22-1 seeds (rad, obl, bia, perm) and the radial-node seed; the pinned shell set to the exact exterior."""
    cfg, delta = T.cfg, T.delta
    if kind == "node":
        n, h = cfg["n"], cfg["h"]
        r = T.r
        a = (1.0 + 2.0 * delta) / 3.0
        r_c, r_n = CORES.R_C, 5.0
        u = ((1.0 - np.exp(-((r / r_c) ** 2))) * (1.0 - 2.0 * np.exp(-((r / r_n) ** 2))))[..., None, None]
        M = B3.embed34(u * T.S_ext + (1.0 - u) * a * EYE3, cfg)
    else:
        M = CORES.seed_core(cfg, kind, delta)
    pin = ~T.free
    Mext = B3.embed34(T.S_ext, cfg)
    M[pin] = Mext[pin]
    return M


