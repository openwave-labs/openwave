def k_census(T: Terms, M, D=None):
    """the per-cell 10 x 10 omega^2 weight (certified + selective) on the free cells: signature histogram."""
    BX = []
    for a in range(4):
        X = np.zeros((4, 4)); X[a, a] = 1.0; BX.append(X)
    for j in range(1, 4):
        X = np.zeros((4, 4)); X[0, j] = X[j, 0] = 1.0; BX.append(X)
    for i, j in [(1, 2), (1, 3), (2, 3)]:
        X = np.zeros((4, 4)); X[i, j] = X[j, i] = 1.0; BX.append(X)
    BX = np.array(BX)
    BW = np.array([np.sum(b * b) for b in BX])
    n, h = T.n, T.h
    Ab = {br: [B3.d1(M, ax, h, br) for ax in range(3)] for br, _ in B3.branches(T.cfg["stencil"])}

    def kc(Xc):
        tot = np.zeros((n, n, n))
        for br, wt in B3.branches(T.cfg["stencil"]):
            for i in range(3):
                F = B3.comm_eta(Xc, Ab[br][i])
                tot += wt * B3.inner_eta(F, F)
        return 4.0 * h**3 * tot

    kx = np.zeros((n, n, n, 10, 10))
    diag = [kc(np.broadcast_to(BX[a], M.shape)) for a in range(10)]
    for a in range(10):
        kx[..., a, a] = diag[a]
        for b in range(a + 1, 10):
            kx[..., a, b] = kx[..., b, a] = 0.5 * (kc(np.broadcast_to(BX[a] + BX[b], M.shape)) - diag[a] - diag[b])
    if T.lam_sel != 0.0:
        if D is None:
            D = disc_and_grad(M, False)[0] / T.K_D
        kx += (0.5 * T.lam_sel * h**3 * D)[..., None, None] * np.diag(BW)[None, None, None]
    k = kx[T.free]
    sw = np.sqrt(BW)
    ko = k / sw[None, :, None] / sw[None, None, :]
    ev = np.linalg.eigvalsh(ko)
    kscale = float(np.max(np.abs(ev)))
    tol = 1e-8 * kscale
    pos, neg = ev > tol, ev < -tol
    nul = ~(pos | neg)
    sig = np.stack([pos.sum(1), neg.sum(1), nul.sum(1)], -1)
    keys, cnt = np.unique(sig, axis=0, return_counts=True)
    return {"K_scale": kscale, "n_pos": int(pos.sum()), "n_neg": int(neg.sum()), "n_null": int(nul.sum()),
            "n_free_cells": int(T.free.sum()),
            "signature_histogram": {f"{int(a)}+/{int(b)}-/{int(c)}0": int(m) for (a, b, c), m in zip(keys, cnt)}}


def radial_profile(T: Terms, field, nb=12):
    rb = np.linspace(0.0, 0.5 * T.L, nb + 1)
    out = []
    for j in range(nb):
        sel = (T.r >= rb[j]) & (T.r < rb[j + 1])
        out.append(float(field[sel].sum()) if sel.any() else 0.0)
    return {"bins_to_L_over_2": rb.tolist(), "sum_per_bin": out}


def reads(T: Terms, M, J, full=True):
    """the per-state record."""
    E, _, parts = T.e_j(M, J, need_grad=False)
    n, h = T.n, T.h
    r = T.r
    e = R20.density(M, T.cfg, T.pot)
    lam = np.linalg.eigvalsh(M[..., 1:, 1:])
    eps = 0.5 * (lam[..., 1] - lam[..., 0])
    a0 = parts["a0"]
    a02 = np.einsum("...ab,...ab->...", a0, a0)
    # the kin density of the certified part (per cell)
    kd = np.zeros((n, n, n))
    for br, wt in B3.branches(T.cfg["stencil"]):
        for i in range(3):
            F = B3.comm_eta(a0, B3.d1(M, i, h, br))
            kd += wt * B3.inner_eta(F, F)
    kd *= 4.0 * h**3
    er = e.ravel()
    o = np.argsort(r.ravel())
    cum = np.cumsum(er[o])
    ko = np.cumsum(kd.ravel()[o])
    far = T.free & (r >= 12.0)
    dS = M[..., 1:, 1:] - T.S_ext
    rec = {
        "J": float(J), "E_J": float(parts["E_J"]), "E_stat": float(parts["E_stat"]), "E_rot": float(parts["E_rot"]),
        "omega": float(parts["omega"]), "kin": float(parts["kin_cert"] + parts["kin_sel"]),
        "kin_cert": float(parts["kin_cert"]), "kin_sel": float(parts["kin_sel"]),
        "E_cert_v4": parts["E_cert_v4"], "V6": parts["V6"], "E_spec": parts["E_spec"], "E_spec_per_p": parts["E_spec_per_p"],
        "E_sel_stat": parts["E_sel_stat"], "E_lift_sx": parts.get("E_lift_sx", 0.0), "E_lift_sel": parts.get("E_lift_sel", 0.0),
        "E_J_over_omega_J": (float(parts["E_J"] / (parts["omega"] * J)) if J > 0 and np.isfinite(parts["omega"]) else None),
        "r_half_energy": float(r.ravel()[o][np.searchsorted(cum, 0.5 * cum[-1])]),
        "r_half_kin": (float(r.ravel()[o][np.searchsorted(ko, 0.5 * ko[-1])]) if ko[-1] > 0 else None),
        "a0_norm2_total": float(a02.sum()), "a0_norm2_max_cell": float(a02.max()),
        "a0_norm2_on_free_cells_r_ge_12": float(a02[far].sum()),
        "biax_eps_max": float(eps.max()), "biax_eps_r_of_max": float(r.ravel()[int(np.argmax(eps))]),
        "lam_top_min": float(lam[..., 2].min()), "lam_small_min": float(lam[..., 0].min()),
        "M00_range": [float(M[..., 0, 0].min()), float(M[..., 0, 0].max())],
        "cond1_rms_S_minus_Sext_free_r_ge_12": float(np.sqrt(np.mean(np.sum(dS[far] ** 2, axis=(-1, -2))))),
        "cond1_max_S_minus_Sext_free_r_ge_12": float(np.sqrt(np.max(np.sum(dS[far] ** 2, axis=(-1, -2))))),
        "e_min_cell": float(e.min()),
    }
    if full:
        deg = R21.degree_surface_reads(M, T.cfg)["rank2"]
        rec["cond1_degree_top"] = {k: {"degree": v["degree"], "surface_conflicts": v["surface_conflicts"],
                                       "solid_angle": v["solid_angle"], "reading": v["reading"]} for k, v in deg.items()}
        rec["profile_energy"] = radial_profile(T, e)
        rec["profile_kin_cert"] = radial_profile(T, kd)
        rec["profile_biax_eps_mean"] = {"r": [], "eps": []}
        for R in np.arange(1.5, 0.5 * T.L - 1.0, 1.5):
            sh = np.abs(r - R) < 0.75 * h
            if sh.any():
                rec["profile_biax_eps_mean"]["r"].append(float(R))
                rec["profile_biax_eps_mean"]["eps"].append(float(eps[sh].mean()))
        rec["cond5_K_census"] = k_census(T, M, parts["D"])
    return rec


