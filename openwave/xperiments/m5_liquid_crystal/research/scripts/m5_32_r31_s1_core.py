# ================= the discriminant as a polynomial in the trace invariants (sympy, once) =================
def _disc_lambdas():
    P1, P2, P3, P4, x = sp.symbols("P1 P2 P3 P4 x")
    e1 = P1
    e2 = (e1 * P1 - P2) / 2
    e3 = (e2 * P1 - e1 * P2 + P3) / 3
    e4 = (e3 * P1 - e2 * P2 + e1 * P3 - P4) / 4
    poly = sp.Poly(x**4 - e1 * x**3 + e2 * x**2 - e3 * x + e4, x)
    disc = sp.expand(sp.discriminant(poly, x))
    grads = [sp.expand(sp.diff(disc, P)) for P in (P1, P2, P3, P4)]
    f = sp.lambdify((P1, P2, P3, P4), disc, "numpy")
    fg = [sp.lambdify((P1, P2, P3, P4), g_, "numpy") for g_ in grads]
    return f, fg, str(disc)


DISC_F, DISC_G, DISC_STR = _disc_lambdas()


def k_d_of(g, delta):
    """Disc at the author's nondegenerate vacuum spectrum (-g, 1, delta, 0)."""
    return float(delta**2 * g**2 * (1.0 - delta) ** 2 * (g + delta) ** 2 * (g + 1.0) ** 2)


# ================= per-cell algebra =================
def traces_pows(M):
    """S_p = tr N^p for p = 1..4 (four arrays) and the powers [I, N, N^2, N^3]."""
    Me = M @ ETA
    pows = [np.broadcast_to(np.eye(4), M.shape).copy()]
    for _ in range(1, 4):
        pows.append(pows[-1] @ Me)
    t = [np.einsum("...kk->...", P @ Me) for P in pows]
    return t, pows


def dSp_dM(pows, k):
    """dS_k / dM along a symmetric increment, before sym4: k (eta N^{k-1})^T."""
    return k * (ETA @ pows[k - 1]).swapaxes(-1, -2)


def disc_poly_and_grad(M, need_grad=True):
    """Disc(N) per cell as the sympy polynomial in S_1..S_4 and its gradient through the trace chain. The declared
    reading of the plan; NUMERICALLY UNUSABLE on this instrument (deviation logged at R31-0: the monomials reach
    g^12 and cancel to zero on the degenerate vacuum, so at g = 8 the value carries 1e-6 absolute noise and the FD
    gate of the reduced gradient fails at 1e-2); kept as the small-g identity control of disc_and_grad."""
    t, pows = traces_pows(M)
    Dr = DISC_F(*t)
    if not need_grad:
        return Dr, None
    G = np.zeros_like(M)
    for k in range(1, 5):
        gk = DISC_G[k - 1](*t)
        G += np.asarray(gk)[..., None, None] * dSp_dM(pows, k)
    return Dr, B3.sym4(G)


_PAIRS = [(i, j) for i in range(4) for j in range(i + 1, 4)]


def disc_and_grad(M, need_grad=True):
    """Disc(N) = prod_{i<j} (lambda_i - lambda_j)^2 per cell on a block-diagonal field, from the eigenvalues
    (lambda_0 = -M_00, the three of the symmetric spatial block by eigh), and its gradient wrt M: the same smooth
    symmetric function of the spectrum as the trace polynomial, evaluated without cancellation. dDisc / dlambda_k is
    assembled from products over the other pairs (no division), so it is exact and finite at a coalescing pair, where
    the two members' derivatives agree and their eigenvector ambiguity drops out of sum_k f_k v_k v_k^T."""
    lam0 = -M[..., 0, 0]
    if need_grad:
        w, V = np.linalg.eigh(M[..., 1:, 1:])
    else:
        w = np.linalg.eigvalsh(M[..., 1:, 1:])
        V = None
    lam = np.concatenate([lam0[..., None], w], axis=-1)
    d = {(i, j): lam[..., i] - lam[..., j] for i, j in _PAIRS}
    d2 = {k: v * v for k, v in d.items()}
    Dr = np.ones(M.shape[:3])
    for k in _PAIRS:
        Dr = Dr * d2[k]
    if not need_grad:
        return Dr, None
    # P_kj = product of the squared differences of the OTHER five pairs
    f = np.zeros(M.shape[:3] + (4,))
    for (i, j) in _PAIRS:
        P = np.ones(M.shape[:3])
        for k in _PAIRS:
            if k != (i, j):
                P = P * d2[k]
        f[..., i] += 2.0 * d[(i, j)] * P
        f[..., j] -= 2.0 * d[(i, j)] * P
    G = np.zeros_like(M)
    G[..., 0, 0] = -f[..., 0]
    G[..., 1:, 1:] = np.einsum("...k,...ak,...bk->...ab", f[..., 1:], V, V)
    return Dr, G


def lift_and_grad(M, g, delta, kind, need_grad=True):
    """the author's lifts (the lepton article, Release 2.0, eqs. (46) and (48)) per cell on a block-diagonal field, from the
    eigenvalues of N = M eta (lambda_0 = -M_00, the spatial three by eigh), in the product form over the DISTINCT vacuum
    eigenvalues of (-g, 1, delta, delta):
      'sx'  : tr[p(N)^2] / (2 D^2),  p(z) = (z + g)(z - 1)(z - delta),  D = |p'(delta)| = (g + delta)(1 - delta)
      'sel' : tr[p_sel(N)^2] / 2,     p_sel(z) = (z + g)^2 (z - 1)^2 (z - delta) / D^2
    Both vanish on the vacuum with zero first variation and cost beta^2 per unit weight for splitting the degenerate pair
    to delta +- beta; the gradient wrt M is assembled as in disc_and_grad (f_k v_k v_k^T, exact at a coalescing pair)."""
    lam0 = -M[..., 0, 0]
    if need_grad:
        w, V = np.linalg.eigh(M[..., 1:, 1:])
    else:
        w = np.linalg.eigvalsh(M[..., 1:, 1:])
        V = None
    lam = np.concatenate([lam0[..., None], w], axis=-1)
    D2 = ((g + delta) * (1.0 - delta)) ** 2
    a, b, c = lam + g, lam - 1.0, lam - delta
    if kind == "sx":
        p = a * b * c
        dp = b * c + a * c + a * b
        pref = 0.5 / D2
    elif kind == "sel":
        p = a * a * b * b * c / D2
        dp = (2.0 * a * b * b * c + 2.0 * a * a * b * c + a * a * b * b) / D2
        pref = 0.5
    else:
        raise ValueError(kind)
    dens = pref * np.sum(p * p, axis=-1)
    if not need_grad:
        return dens, None
    f = pref * 2.0 * p * dp
    G = np.zeros_like(M)
    G[..., 0, 0] = -f[..., 0]
    G[..., 1:, 1:] = np.einsum("...k,...ak,...bk->...ab", f[..., 1:], V, V)
    return dens, G


def rhat_generator(cfg):
    """G_r(x): the so(3) generator of the rotation about r-hat(x), embedded in the spatial block (antisymmetric)."""
    n, h = cfg["n"], cfg["h"]
    X, Y, Z = B3.coords(n, h)
    r = np.sqrt(X * X + Y * Y + Z * Z)
    rx, ry, rz = X / r, Y / r, Z / r
    G = np.zeros((n, n, n, 4, 4))
    G[..., 1, 2], G[..., 2, 1] = -rz, rz
    G[..., 1, 3], G[..., 3, 1] = ry, -ry
    G[..., 2, 3], G[..., 3, 2] = -rx, rx
    return G


def a0_of(M, Gr):
    return Gr @ M - M @ Gr


def s_ext_of(cfg, delta):
    n, h = cfg["n"], cfg["h"]
    X, Y, Z = B3.coords(n, h)
    r = np.sqrt(X * X + Y * Y + Z * Z)
    rh = np.stack([X, Y, Z], axis=-1) / r[..., None]
    return delta * EYE3 + (1.0 - delta) * rh[..., :, None] * rh[..., None, :]


# ================= the terms =================
class Terms:
    """the S1 functional at one parameter point on one box: energies, kin and their full symmetric gradients."""

    def __init__(self, n, L, g, delta, w1s, c6=0.0, lam_s=0.0, lam_sel=0.0, eps_sx=0.0, eps_sel=0.0):
        self.n, self.L, self.g, self.delta, self.w1s = int(n), float(L), float(g), float(delta), float(w1s)
        self.c6, self.lam_s, self.lam_sel = float(c6), float(lam_s), float(lam_sel)
        self.eps_sx, self.eps_sel = float(eps_sx), float(eps_sel)  # the author's lifts, Release 2.0 eqs. (46), (48)
        self.cfg = R21.cfg_of(self.n, self.L, self.g, self.delta)
        self.h = self.cfg["h"]
        self.h3 = self.h**3
        self.p = R21.params_of(self.g, self.delta)
        self.roots = R0.roots_of(self.cfg, degenerate=True)
        self.w = W1 * self.w1s
        self.pot = ("v4", self.roots, self.w)
        self.K_D = k_d_of(self.g, self.delta)
        self.Gr = rhat_generator(self.cfg)
        self.gate = C23.gate_of(self.delta)
        self.free = ~B3.pin_shell(self.n, self.h)
        X, Y, Z = B3.coords(self.n, self.h)
        self.r = np.sqrt(X * X + Y * Y + Z * Z)
        self.S_ext = s_ext_of(self.cfg, self.delta)

    # ---- the static pieces ----
    def cert_v4(self, M, need_grad=True):
        E, G, info = R20.energy_grad(M, self.cfg, self.p, self.pot, need_grad)
        return E, G, info

    def v6(self, M, need_grad=True):
        if self.c6 == 0.0:
            return 0.0, (np.zeros_like(M) if need_grad else None)
        S = M[..., 1:, 1:]
        Q = S - (np.einsum("...ii->...", S) / 3.0)[..., None, None] * EYE3
        Q2 = Q @ Q
        I2 = np.einsum("...ii->...", Q2)
        I3 = np.einsum("...ii->...", Q2 @ Q)
        dens = I2**3 - 6.0 * I3**2
        E = self.c6 * self.h3 * float(np.sum(dens))
        if not need_grad:
            return E, None
        Q2d = Q2 - (I2 / 3.0)[..., None, None] * EYE3
        G3 = (6.0 * I2**2)[..., None, None] * Q - (36.0 * I3)[..., None, None] * Q2d
        G = np.zeros_like(M)
        G[..., 1:, 1:] = self.c6 * self.h3 * G3
        return E, G

    def lifts(self, M, need_grad=True):
        """E_lift = eps w h^3 sum_cells (lift density), one per kind; eps in units of the base weight w = W1 w1s."""
        E, G = 0.0, (np.zeros_like(M) if need_grad else None)
        parts = {"E_lift_sx": 0.0, "E_lift_sel": 0.0}
        for kind, eps, key in (("sx", self.eps_sx, "E_lift_sx"), ("sel", self.eps_sel, "E_lift_sel")):
            if eps == 0.0:
                continue
            dens, Gd = lift_and_grad(M, self.g, self.delta, kind, need_grad)
            Ek = eps * self.w * self.h3 * float(np.sum(dens))
            parts[key] = Ek
            E += Ek
            if need_grad:
                G += (eps * self.w * self.h3) * Gd
        return E, G, parts

    def spec(self, M, t=None, pows=None, need_grad=True):
        """E_spec = (lam_s / 2) h^3 sum_br wt sum_i sum_p (d_i S_p)^2 and its gradient; the per-p split returned."""
        if self.lam_s == 0.0:
            return 0.0, (np.zeros_like(M) if need_grad else None), [0.0] * 4
        if t is None:
            t, pows = traces_pows(M)
        E = 0.0
        per_p = [0.0] * 4
        dEdt = [np.zeros(M.shape[:3]) for _ in range(4)]
        for br, wt in B3.branches(self.cfg["stencil"]):
            for i in range(3):
                for k in range(4):
                    d = B3.d1(t[k], i, self.h, br)
                    ek = wt * 0.5 * self.lam_s * self.h3 * float(np.sum(d * d))
                    E += ek
                    per_p[k] += ek
                    if need_grad:
                        dEdt[k] += wt * self.lam_s * self.h3 * B3.d1_adj(d, i, self.h, br)
        if not need_grad:
            return E, None, per_p
        G = np.zeros_like(M)
        for k in range(1, 5):
            G += dEdt[k - 1][..., None, None] * dSp_dM(pows, k)
        return E, B3.sym4(G), per_p

    def sel_static(self, M, D=None, GD=None, need_grad=True):
        """E_sel,stat = (lam_sel / 2) h^3 sum_x D sum_br wt sum_i tr(A_i A_i) and its gradient."""
        if self.lam_sel == 0.0:
            return 0.0, (np.zeros_like(M) if need_grad else None)
        if D is None:
            Dr, GD = disc_and_grad(M, need_grad)
            D = Dr / self.K_D
            GD = None if GD is None else GD / self.K_D
        grad2 = np.zeros(M.shape[:3])
        G = np.zeros_like(M)
        for br, wt in B3.branches(self.cfg["stencil"]):
            for i in range(3):
                A = B3.d1(M, i, self.h, br)
                grad2 += wt * np.einsum("...ab,...ab->...", A, A)
                if need_grad:
                    G += wt * B3.d1_adj(D[..., None, None] * A, i, self.h, br)
        E = 0.5 * self.lam_sel * self.h3 * float(np.sum(D * grad2))
        if not need_grad:
            return E, None
        G = self.lam_sel * self.h3 * G + 0.5 * self.lam_sel * self.h3 * grad2[..., None, None] * GD
        return E, B3.sym4(G)

    def e_stat(self, M, need_grad=True):
        """E_stat and its full gradient, with the parts."""
        E1, G1, info = self.cert_v4(M, need_grad)
        if not np.isfinite(E1) or (need_grad and G1 is None) or not info.get("ok", True):
            return np.nan, None, {"ok": False}
        t, pows = traces_pows(M)
        D = GD = None
        if self.lam_sel != 0.0:
            Dr, GDr = disc_and_grad(M, need_grad)
            D = Dr / self.K_D
            GD = None if GDr is None else GDr / self.K_D
        E6, G6 = self.v6(M, need_grad)
        Es, Gs, per_p = self.spec(M, t, pows, need_grad)
        Eq, Gq = self.sel_static(M, D, GD, need_grad)
        El, Gl, lp = self.lifts(M, need_grad)
        E = E1 + E6 + Es + Eq + El
        G = None if not need_grad else G1 + G6 + Gs + Gq + Gl
        parts = {"E_cert_v4": float(E1), "V6": float(E6), "E_spec": float(Es), "E_spec_per_p": per_p,
                 "E_sel_stat": float(Eq), "ok": True, "D": D, "GD": GD, "t": t, "pows": pows}
        parts.update(lp)
        return float(E), G, parts

    # ---- the clock ----
    def kin(self, M, D=None, GD=None, need_grad=True):
        """kin = kin_cert + kin_sel and the full gradient wrt M (a0 = [G_r, M] moving with M)."""
        a0 = a0_of(M, self.Gr)
        h3, h = self.h3, self.h
        E_c = 0.0
        G = np.zeros_like(M) if need_grad else None
        Ga0 = np.zeros_like(M) if need_grad else None
        a0E_T = (a0 @ ETA).swapaxes(-1, -2)
        Ea0_T = (ETA @ a0).swapaxes(-1, -2)
        for br, wt in B3.branches(self.cfg["stencil"]):
            for i in range(3):
                A = B3.d1(M, i, h, br)
                F = B3.comm_eta(a0, A)
                E_c += wt * float(np.sum(B3.inner_eta(F, F)))
                if need_grad:
                    W = 2.0 * (ETA @ F @ ETA)
                    dAi = a0E_T @ W - W @ Ea0_T
                    G += wt * B3.d1_adj(dAi, i, h, br)
                    Ga0 += wt * (W @ A @ ETA - ETA @ A @ W)
        kin_c = 4.0 * h3 * E_c
        kin_s = 0.0
        if self.lam_sel != 0.0:
            if D is None:
                Dr, GDr = disc_and_grad(M, need_grad)
                D = Dr / self.K_D
                GD = None if GDr is None else GDr / self.K_D
            a02 = np.einsum("...ab,...ab->...", a0, a0)
            kin_s = 0.5 * self.lam_sel * h3 * float(np.sum(D * a02))
        if not need_grad:
            return kin_c + kin_s, None, {"kin_cert": kin_c, "kin_sel": kin_s, "a0": a0}
        G = 4.0 * h3 * G
        Ga0 = 4.0 * h3 * Ga0
        if self.lam_sel != 0.0:
            Ga0 = Ga0 + self.lam_sel * h3 * D[..., None, None] * a0
            G = G + 0.5 * self.lam_sel * h3 * a02[..., None, None] * GD
        G = G + (Ga0 @ self.Gr - self.Gr @ Ga0)
        return kin_c + kin_s, B3.sym4(G), {"kin_cert": kin_c, "kin_sel": kin_s, "a0": a0}

    def e_j(self, M, J, need_grad=True):
        """E_J = E_stat + J^2 / (4 kin) with the full gradient and the parts."""
        E, G, parts = self.e_stat(M, need_grad)
        if not parts.get("ok", False):
            return np.nan, None, parts
        k, Gk, kp = self.kin(M, parts["D"], parts["GD"], need_grad)
        parts.update(kp)
        parts["E_stat"] = E
        if J == 0.0:
            parts.update(E_rot=0.0, omega=0.0, E_J=E)
            return E, G, parts
        if k <= 0.0:
            parts.update(E_rot=np.inf, omega=np.inf, E_J=np.inf, kin_nonpositive=True)
            return np.inf, None, parts
        E_rot = J * J / (4.0 * k)
        parts.update(E_rot=E_rot, omega=J / (2.0 * k), E_J=E + E_rot)
        if not need_grad:
            return E + E_rot, None, parts
        return E + E_rot, G - (J * J / (4.0 * k * k)) * Gk, parts


# ================= the slaved reduction =================
class Reduced:
    """L-BFGS variables: the six spatial entries per free cell; M_00 slaved to V4 per cell; the reduced gradient with
    the implicit-function term for the M_00-dependent nonlocal terms."""

    def __init__(self, T: Terms, M, J, pinned=True):
        self.T, self.J = T, float(J)
        self.mask = R21.free_mask(T.cfg, pinned)
        self.M = M.copy()
        self.last = None
        self.n_eval = 0

    def build(self, x):
        M = self.M.copy()
        S = M[..., 1:, 1:].copy()
        blk = np.zeros((int(self.mask.sum()), 3, 3), dtype=float)
        blk[:, IU3[0], IU3[1]] = x.reshape(-1, 6)
        blk = blk + blk.swapaxes(-1, -2) - np.einsum("...ii->...i", blk)[..., None] * EYE3
        S[self.mask] = blk
        M[..., 1:, 1:] = S
        m00 = M[..., 0, 0].copy()
        m00[self.mask] = SL.solve_m00(S[self.mask], self.T.roots, m00[self.mask])
        M[..., 0, 0] = m00
        return M

    def pack(self, M):
        return M[..., 1:, 1:][self.mask][:, IU3[0], IU3[1]].ravel().copy()

    def chain(self, M):
        """dM_00 / dS on the free cells, (nfree, 3, 3): (d^2 V4 / du dS) / (d^2 V4 / du^2), u = -M_00."""
        S = M[..., 1:, 1:][self.mask]
        u = -M[..., 0, 0][self.mask]
        w, roots = self.T.w, self.T.roots
        cp = [sum(q**k for q in roots) for k in range(1, 5)]
        s, Sp = [], [np.broadcast_to(EYE3, S.shape)]
        P = S
        for k in range(1, 5):
            if k > 1:
                P = P @ S
            s.append(np.einsum("...kk->...", P))
            Sp.append(P)
        H = np.zeros_like(u)
        C = np.zeros_like(S)
        for k in range(1, 5):
            r = u**k + s[k - 1] - cp[k - 1]
            d = k * u ** (k - 1)
            dd = k * (k - 1) * u ** (k - 2) if k > 1 else 0.0 * u
            H += 2.0 * w * (d * d + r * dd)
            C += (2.0 * w * d)[..., None, None] * (k * Sp[k - 1])
        return C / H[..., None, None]

    def fun(self, x):
        self.n_eval += 1
        M = self.build(x)
        E, Gm, parts = self.T.e_j(M, self.J, True)
        if Gm is None or not np.isfinite(E):
            self.last = None
            return 1e30, np.zeros_like(x)
        Gf = Gm[self.mask]
        G3 = Gf[:, 1:, 1:].copy()
        if self.T.lam_s != 0.0 or self.T.lam_sel != 0.0 or self.T.eps_sx != 0.0 or self.T.eps_sel != 0.0:
            G3 += Gf[:, 0, 0][..., None, None] * self.chain(M)
        gs = G3[:, IU3[0], IU3[1]] * OFF3
        self.last = (float(E), float(np.max(np.abs(G3))), float(np.max(np.abs(Gf[:, 0, 0]))), parts)
        self.M[..., 0, 0] = M[..., 0, 0]
        return float(E), gs.ravel()

    def fd_gate(self, M, ndir=3, t=1e-4, seed=31):
        """the Richardson pair of central differences of the reduced functional against g . v."""
        x0 = self.pack(M)
        E0, g0 = self.fun(x0)
        rng = np.random.default_rng(seed)
        rows = []
        for _ in range(ndir):
            v = rng.normal(size=x0.shape)
            v /= np.linalg.norm(v)
            d1 = (self.fun(x0 + t * v)[0] - self.fun(x0 - t * v)[0]) / (2 * t)
            d2 = (self.fun(x0 + 0.5 * t * v)[0] - self.fun(x0 - 0.5 * t * v)[0]) / t
            num = (4 * d2 - d1) / 3.0
            an = float(g0 @ v)
            rows.append({"analytic": an, "fd_richardson": num, "fd_pair": [d1, d2],
                         "rel_err": abs(num - an) / max(abs(num), 1e-300)})
        return {"E": E0, "rows": rows, "max_rel_err": max(r_["rel_err"] for r_ in rows)}


