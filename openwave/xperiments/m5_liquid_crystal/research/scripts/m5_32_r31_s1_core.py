def job_tag(j):
    return (f"{j['pid']}_{j['seed']}_J{j['J']:.6g}_n{j['n']}_L{j['L']:g}_g{j['g']:.4g}_d{j['delta']:.4g}"
            f"_w{j['w1s']:.4g}_c6{j['c6']:.3g}_ls{j['lam_s']:.3g}_lsel{j['lam_sel']:.3g}"
            + (f"_sx{j['eps_sx']:.3g}" if j.get("eps_sx", 0.0) else "") + (f"_sel{j['eps_sel']:.3g}" if j.get("eps_sel", 0.0) else ""))


def relax(j, M0, out_dir=OUT_NPZ, max_iter=None, log_prefix="", ug=None):
    """one relaxation at fixed J from the start field M0 (the pinned shell is taken from M0); resumable stage file;
    returns (M, row). j: pid, seed, J, n, L, g, delta, w1s, c6, lam_s, lam_sel, eps_sx, eps_sel."""
    from scipy.optimize import minimize

    t0 = time.time()
    T = Terms(j["n"], j["L"], j["g"], j["delta"], j["w1s"], j["c6"], j["lam_s"], j["lam_sel"], j.get("eps_sx", 0.0), j.get("eps_sel", 0.0))
    tag = job_tag(j)
    os.makedirs(out_dir, exist_ok=True)
    stage = os.path.join(out_dir, tag + "_stage.npz")
    cap = max_iter or MAX_ITER.get(T.n, 4000)
    row = dict(j, tag=tag, gate=T.gate, K_D=T.K_D)
    if os.path.exists(stage):
        Zs = np.load(stage, allow_pickle=True)
        M, done, chunks = Zs["M"], int(Zs["done"]), json.loads(str(Zs["chunks"]))
    else:
        M = M0.copy()
        if np.abs(M[..., 0, 1:]).max() > 0:
            raise RuntimeError("the start field is not block-diagonal")
        done, chunks = 0, []
    red = Reduced(T, M, j["J"], True)
    E0, _ = red.fun(red.pack(M))
    if not chunks:
        chunks = [dict(reads(T, red.build(red.pack(M)), j["J"], full=False), iters=0, note="start field")]
    verdict = "FALLING"
    while done < cap:
        red = Reduced(T, M, j["J"], True)
        st = {"it": 0, "gate_hit": None}

        def cb(xk, red=red, st=st):
            st["it"] += 1
            if st["it"] >= 5 and red.last is not None and red.last[1] < T.gate:
                st["gate_hit"] = st["it"]

        res = minimize(red.fun, red.pack(M), jac=True, method="L-BFGS-B", callback=cb,
                       options={"maxcor": 20, "maxiter": CHUNK, "maxfun": 3 * CHUNK, "gtol": 1e-14, "ftol": 1e-16})
        M = red.build(np.asarray(res.x))
        done += max(1, st["it"])
        E, gs = red.fun(red.pack(M))
        rec = dict(reads(T, M, j["J"], full=False), iters=done, fmax_spatial=red.last[1], fmax_M00=red.last[2],
                   gate_hit_inside_chunk=st["gate_hit"], chunk_iters=st["it"], scipy=str(res.message))
        rec["drop"] = chunks[-1]["E_J"] - rec["E_J"]
        chunks.append(rec)
        np.savez_compressed(stage, M=M, done=done, chunks=json.dumps(chunks))
        log(f"{log_prefix}{tag} its {done} E_J {rec['E_J']:.6g} (stat {rec['E_stat']:.5g} rot {rec['E_rot']:.4g} "
            f"w* {rec['omega']:.4g} kin {rec['kin']:.4g}) drop {rec['drop']:.2e} fmax {rec['fmax_spatial']:.2e} "
            f"(gate {T.gate:.1e}) eps_max {rec['biax_eps_max']:.3f}")
        if rec["fmax_spatial"] < T.gate and 0 <= rec["drop"] < GATE_DROP * abs(rec["E_J"]) and st["it"] >= 5:
            verdict = "AT_GATE"
            break
        if st["it"] < 5 and rec["drop"] <= 0:
            verdict = "LINE_SEARCH_STALL"
            break
        if ug is not None and ug.wrap_up():
            verdict = "UPS wrap-up (resumable)"
            break
    final = reads(T, M, j["J"], full=True)
    row.update(chunks=chunks, iters=done, label=verdict, final=final, E_J=final["E_J"], status="OK",
               wall_s=round(time.time() - t0, 1), n_eval=sum(c.get("chunk_iters", 0) for c in chunks))
    np.savez_compressed(os.path.join(out_dir, tag + ".npz"), M=M)
    log(f"{log_prefix}DONE {tag} {verdict} E_J {final['E_J']:.6g} wall {row['wall_s']}")
    return M, row


def goldstone_omega(T: Terms):
    """the lattice Goldstone of the pinned box: omega_G^2 = 3 (2/h sin(pi h / 2 L_free))^2 (R29-1's control-gold)."""
    wc = int(np.ceil(1.6 / T.h))
    Lf = (T.n - 2 * wc + 1) * T.h
    k1 = 2.0 / T.h * np.sin(np.pi / Lf * T.h / 2)
    return float(np.sqrt(3.0) * k1), float(Lf)
