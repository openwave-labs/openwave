def interp_field(Ms, n_new):
    """a stored field moved to another grid at the same spacing by order-1 zoom (R29-1's warm start)."""
    from scipy.ndimage import zoom

    f = n_new / Ms.shape[0]
    return np.stack([np.stack([zoom(Ms[..., a, b], f, order=1) for b in range(4)], -1) for a in range(4)], -2)


